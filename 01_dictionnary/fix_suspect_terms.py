def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("extract", help="write the vim review file")
    p_apply = sub.add_parser("apply", help="execute the edited review file")
    p_apply.add_argument("--apply", action="store_true", help="actually write (default: dry run)")
    p_apply.add_argument("--skip-audio", action="store_true",
                         help="do not touch the SSD clips (e.g. SSD not mounted)")
    args = ap.parse_args()
    if args.cmd == "extract":
        return cmd_extract()
    return cmd_apply(args.apply, args.skip_audio)


if __name__ == "__main__":
    raise SystemExit(main())
